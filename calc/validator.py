"""Syntax and safety validation for calculator expressions.

The validator is the security boundary of the application: every expression,
whether typed by the user or (in Phase 2) generated by an LLM, must pass
through :func:`validate` before it reaches the math engine.
"""

import re

from calc.exceptions import ValidationError

#: Maximum accepted expression length, in characters (after stripping).
MAX_LENGTH = 200

#: Unicode / calculator-style symbols mapped to their Python equivalents.
_REPLACEMENTS = {
    "×": "*",
    "÷": "/",
    "−": "-",
    "π": "pi",
    "√": "sqrt",
    "^": "**",
}

#: Characters permitted after normalisation.
_ALLOWED_CHARS = re.compile(r"^[0-9a-z_.+\-*/%()\s,]*$")


def normalize(expression: str) -> str:
    """Convert calculator-style notation into Python syntax.

    Replaces symbols such as ``×``, ``÷``, ``π`` and ``^`` with their Python
    equivalents and lower-cases the text so that ``Sin(PI)`` is accepted.

    Args:
        expression: Raw expression as entered by the user.

    Returns:
        The normalised expression string, stripped of surrounding whitespace.
    """
    text = expression.strip().lower()
    for symbol, replacement in _REPLACEMENTS.items():
        text = text.replace(symbol, replacement)
    return text


def validate(expression: str) -> str:
    """Validate an expression and return its normalised form.

    Args:
        expression: Raw expression as entered by the user.

    Returns:
        The normalised expression, safe to hand to the parser.

    Raises:
        ValidationError: If the expression is empty, too long or contains
            characters outside the allowed set.
    """
    if not isinstance(expression, str):
        raise ValidationError("Expression must be text.")

    text = normalize(expression)
    if not text:
        raise ValidationError("Please enter an expression.")
    if len(text) > MAX_LENGTH:
        raise ValidationError(f"Expression is too long (max {MAX_LENGTH} characters).")
    if not _ALLOWED_CHARS.match(text):
        raise ValidationError("Expression contains invalid characters.")
    return text
