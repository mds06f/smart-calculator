"""Syntax and safety validation for calculator expressions.

The validator is the security boundary of the application: every expression,
whether typed by the user or (in Phase 2) generated by an LLM, must pass
through :func:`validate` before it reaches the math engine.
"""

import ast
import re

from calc.exceptions import ValidationError

#: Maximum accepted expression length, in characters (after stripping).
MAX_LENGTH = 200

#: Maximum number of AST nodes, guarding against deeply nested input.
MAX_NODES = 100

#: Functions callable from an expression (single positional argument each).
ALLOWED_FUNCTIONS = frozenset(
    {
        "sqrt", "abs", "exp", "ln", "log", "log10",
        "sin", "cos", "tan", "asin", "acos", "atan",
        "factorial",
    }
)

#: Named constants usable in an expression.
ALLOWED_CONSTANTS = frozenset({"pi", "e"})

#: Permitted binary and unary operators.
ALLOWED_BINARY_OPS = (ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Pow, ast.Mod)
ALLOWED_UNARY_OPS = (ast.UAdd, ast.USub)

#: Unicode / calculator-style symbols mapped to their Python equivalents.
_REPLACEMENTS = {
    "×": "*",
    "÷": "/",
    "−": "-",
    "π": "pi",
    "√": "sqrt",
    "^": "**",
}

#: Characters permitted after normalisation.
_ALLOWED_CHARS = re.compile(r"^[0-9a-z_.+\-*/%()\s,]*$")


def normalize(expression: str) -> str:
    """Convert calculator-style notation into Python syntax.

    Replaces symbols such as ``×``, ``÷``, ``π`` and ``^`` with their Python
    equivalents and lower-cases the text so that ``Sin(PI)`` is accepted.

    Args:
        expression: Raw expression as entered by the user.

    Returns:
        The normalised expression string, stripped of surrounding whitespace.
    """
    text = expression.strip().lower()
    for symbol, replacement in _REPLACEMENTS.items():
        text = text.replace(symbol, replacement)
    return text


def _check_node(node: ast.AST) -> None:
    """Recursively ensure every AST node belongs to the safe subset.

    Args:
        node: The AST node to inspect.

    Raises:
        ValidationError: If a node type, operator, name or function call is
            outside the whitelist.
    """
    if isinstance(node, ast.Expression):
        _check_node(node.body)
    elif isinstance(node, ast.Constant):
        # bool is a subclass of int, so exclude it explicitly.
        if isinstance(node.value, bool) or not isinstance(node.value, (int, float)):
            raise ValidationError("Only numeric literals are allowed.")
    elif isinstance(node, ast.BinOp):
        if not isinstance(node.op, ALLOWED_BINARY_OPS):
            raise ValidationError("Unsupported operator.")
        _check_node(node.left)
        _check_node(node.right)
    elif isinstance(node, ast.UnaryOp):
        if not isinstance(node.op, ALLOWED_UNARY_OPS):
            raise ValidationError("Unsupported operator.")
        _check_node(node.operand)
    elif isinstance(node, ast.Name):
        if node.id not in ALLOWED_CONSTANTS:
            raise ValidationError(f"Unknown name '{node.id}'.")
    elif isinstance(node, ast.Call):
        if not isinstance(node.func, ast.Name) or node.func.id not in ALLOWED_FUNCTIONS:
            raise ValidationError("Unknown or unsupported function.")
        if node.keywords:
            raise ValidationError("Keyword arguments are not allowed.")
        if len(node.args) != 1:
            raise ValidationError(f"'{node.func.id}' takes exactly one argument.")
        _check_node(node.args[0])
    else:
        raise ValidationError("Expression contains unsupported syntax.")


def validate(expression: str) -> ast.Expression:
    """Validate an expression and return its safe abstract syntax tree.

    The expression is normalised, checked against a character whitelist,
    parsed with :mod:`ast` (never executed) and then walked to ensure it only
    uses whitelisted numbers, operators, constants and functions.

    Args:
        expression: Raw expression as entered by the user.

    Returns:
        The parsed :class:`ast.Expression`, ready for the math engine.

    Raises:
        ValidationError: If the expression is empty, too long, contains
            invalid characters, has a syntax error or uses disallowed
            constructs.
    """
    if not isinstance(expression, str):
        raise ValidationError("Expression must be text.")

    text = normalize(expression)
    if not text:
        raise ValidationError("Please enter an expression.")
    if len(text) > MAX_LENGTH:
        raise ValidationError(f"Expression is too long (max {MAX_LENGTH} characters).")
    if not _ALLOWED_CHARS.match(text):
        raise ValidationError("Expression contains invalid characters.")

    try:
        tree = ast.parse(text, mode="eval")
    except SyntaxError as exc:
        raise ValidationError("Invalid syntax.") from exc

    if sum(1 for _ in ast.walk(tree)) > MAX_NODES:
        raise ValidationError("Expression is too complex.")

    _check_node(tree)
    return tree
